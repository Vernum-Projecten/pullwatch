    @Test(arguments: fixtures)
    func `Each install records the registry its lockfile names`(_ fixture: Fixture) throws {
        let found = DependencyDetector.installs([(fixture.path, fixture.content)]).dependencies
        let install = try #require(found.first { $0.name == fixture.name })

        #expect(install.registry == fixture.registry)
        #expect(install.install.registry == fixture.registry)
    }

    @Test func `A token in an index URL never reaches the report`() throws {
        let found = DependencyDetector.installs([("requirements.txt", "--index-url https://user:glpat-s3cr3t@gitlab.com/api/v4/projects/42/packages/pypi/simple?token=x\nacme-billing==1.4.0")])
        let install = try #require(found.dependencies.first)
        let encoded = String(decoding: try JSONEncoder().encode(install.install), as: UTF8.self)

        #expect(!encoded.contains("glpat"))
        #expect(!encoded.contains("token=x"))
        #expect(!encoded.contains("user"))
    }

    @Test func `An install from before #214 reads without a registry`() throws {
        let old = #"{"version":"1.0.0","workspace":"","scope":"direct","kind":"runtime","via":[],"source":"package-lock.json"}"#
        let install = try JSONDecoder().decode(PackageInstall.self, from: Data(old.utf8))

        #expect(install.registry == nil)
    }
