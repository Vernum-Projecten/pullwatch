/// yarn.lock, pnpm-lock.yaml, packages.lock.json en Gemfile.lock: installs met workspace, scope,
/// soort en via, met fixtures in de vorm die de tools zelf schrijven.
@Suite struct LockfileTests {
    /// "naam@versie workspace scope soort via" per install, gesorteerd.
    private func describe(_ dependencies: [Dependency]) -> [String] {
        dependencies.map { d in
            let workspace = d.workspace.isEmpty ? "." : d.workspace
            return "\(d.name)@\(d.version) \(workspace) \(d.scope.rawValue) \(d.kind.rawValue) \(d.via.joined(separator: ">"))"
                .trimmingCharacters(in: .whitespaces)
        }.sorted()
    }

    private func installs(_ files: [String: String]) -> [Dependency] {
        DependencyDetector.installs(files.sorted { $0.key < $1.key }.map { ($0.key, $0.value) }).dependencies
    }

    // MARK: Outline

    @Test func outlineReadsTheYamlSubsetPnpmUses() {
        let tree = Outline.parse("""
        lockfileVersion: '9.0'

        # opmerking
        importers:
          .:
            dependencies:
              '@types/node':
                specifier: ^20.0.0
                version: 20.17.6
        packages:
          'it''s@1.0.0':
            resolution: {integrity: sha512-abc==}
            os: [darwin]
          js-tokens@4.0.0: {}
        """)
        #expect(tree.map(\.key) == ["lockfileVersion", "importers", "packages"])
        #expect(tree[0].value == "9.0")
        let node = tree[1]["."]?["dependencies"]?["@types/node"]
        #expect(node?["specifier"]?.value == "^20.0.0")
        #expect(node?["version"]?.value == "20.17.6")
        #expect(tree[2].children.map(\.key) == ["it's@1.0.0", "js-tokens@4.0.0"])
        #expect(tree[2].children[0]["resolution"]?.value == "{integrity: sha512-abc==}")
        #expect(tree[2].children[1].value == "{}")
    }

    @Test func outlineReadsYarnClassicLines() {
        let tree = Outline.parse("""
        "@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":
          version "7.12.13"
          dependencies:
            "@babel/highlight" "^7.12.13"
            js-tokens "^4.0.0"
        """)
        #expect(tree.count == 1)
        #expect(tree[0].rawKey == #""@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4""#)
        #expect(tree[0].key == tree[0].rawKey)
        #expect(tree[0]["version"]?.value == "7.12.13")
        #expect(tree[0]["dependencies"]?.children.map { "\($0.key)=\($0.value ?? "")" } == ["@babel/highlight=^7.12.13", "js-tokens=^4.0.0"])
    }

